test('export/import du calendrier, anciennes sauvegardes et import invalide', async ({ page }, testInfo) => {
  await page.locator('#settingsBtn').click();
  await page.locator('#Q1Start').fill('2026-09-01');
  await page.locator('#Q1End').fill('2027-01-31');
  await saveSettings(page);
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#exportBtn').click();
  const download = await downloadPromise;
  const path = testInfo.outputPath('backup.json');
  await download.saveAs(path);
  const saved = JSON.parse(await fs.readFile(path, 'utf8'));
  expect(saved.calendar.quarters.Q1.start).toBe('2026-09-01');
  page.on('dialog', dialog => dialog.accept());
  await page.locator('#importInput').setInputFiles(path);
  await expect(page.locator('#noticeText')).toContainText('Sauvegarde importée');
  await page.reload();
  expect((await readState(page)).calendar).toEqual(saved.calendar);
  const invalid = structuredClone(saved);
  invalid.calendar.quarters.Q1.end = '2026-02-30';
  const rejected = page.waitForEvent('dialog');
  await page.locator('#importInput').setInputFiles({ name:'invalid.json', mimeType:'application/json', buffer:Buffer.from(JSON.stringify(invalid)) });
  expect((await rejected).message()).toContain('invalide');
  expect((await readState(page)).calendar).toEqual(saved.calendar);
  delete saved.calendar;
  const imported = page.waitForFunction(() => document.getElementById('noticeText').textContent.includes('Sauvegarde importée'));
  await page.locator('#importInput').setInputFiles({ name:'old.json', mimeType:'application/json', buffer:Buffer.from(JSON.stringify(saved)) });
  await imported;
  await expect.poll(async () => (await readState(page)).calendar.quarters.Q1.start).toBe('');
});
test('nouveaux réglages et encodage disponibles hors ligne sans erreur JS', async ({ page, context }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.waitForFunction(() => !!navigator.serviceWorker.controller);
  await context.setOffline(true);
  await page.reload();
  await page.locator('#settingsBtn').click();
  await expect(course(page, 'web')).toBeVisible();
  await page.locator('#cancelCourseBtn').click();
  await page.locator('#batchBtn').click();
  await page.locator('#batchSave').click();
  await expect(page.locator('#historyList .history-item')).toHaveCount(1);
  await page.reload();
  await expect(page.locator('#historyList .history-item')).toHaveCount(1);
  expect(errors).toEqual([]);
});
test('un calendrier local endommagé ne supprime pas les présences existantes', async ({ page }) => {
  await page.locator('#coursesGrid .quick-present').first().click();
  await page.evaluate(() => {
    const state = JSON.parse(localStorage.getItem('presenceCours.v1'));
    state.calendar = { quarters: null, holidays: [] };
    localStorage.setItem('presenceCours.v1', JSON.stringify(state));
  });
  await page.reload();
  await expect(page.locator('#historyList .history-item')).toHaveCount(1);
  await page.locator('#settingsBtn').click();
  await expect(page.locator('#Q1Start')).toHaveValue('');
  await saveSettings(page);
  await page.reload();
  await expect(page.locator('#historyList .history-item')).toHaveCount(1);
});
